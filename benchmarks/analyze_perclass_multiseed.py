#!/usr/bin/env python3
"""Aggregate per-class precision/recall/F1 across 3 seeds for a target model.

Addresses Reviewer-2 concern #9: per-class metrics currently reported only
for seed 42.

Default target: 1j (MynaNet) under the 80:10:10 protocol.

Reads:  ../mynanet/results_mygardenbird_1_linux/<model>_*_rand{42,100,786}_*split80:10:10*/classification_report_int8.txt
Writes: perclass_multiseed_<model>.csv  +  perclass_multiseed_<model>.tex
        (a LaTeX-ready booktabs table with mean ± std per class)

Usage:
    python3 analyze_perclass_multiseed.py                   # default = 1j
    python3 analyze_perclass_multiseed.py 1e 1i 1p          # multiple models
"""
from __future__ import annotations
import os
import re
import sys
from pathlib import Path
import statistics

# Portable: default to the results tree next to this script's parent
# (Conda/mynanet/results_mygardenbird_1_linux), overridable via env var so
# the same script works on the macOS laptop and the Linux/CUDA box.
RESULTS_ROOT = Path(
    os.environ.get(
        "RESULTS_ROOT_1",
        Path(__file__).resolve().parents[1] / "results_mygardenbird_1_linux",
    )
)
SEEDS = (42, 100, 786, 7, 2024)  # extended to n=5 for the friendly-R2 E2 hardening

MODEL_DIR_PATTERN = {
    "1a": "1a_baseline_standardcnn_mels64_drop05_rand{seed}_warm70_mixup0.2_split80_10_10_linux",
    "1b": "1b_baseline_dscnn_mels64_drop05_rand{seed}_warm70_mixup0.2_split80_10_10_linux",
    "1c": "1c_dscnn_se_mels64_drop05_rand{seed}_warm70_mixup0.2_split80:10:10_linux",
    "1d": "1d_dscnn_res_mels64_drop05_rand{seed}_warm70_mixup0.2_split80:10:10_linux",
    "1e": "1e_dscnn_se_res_mels64_drop05_rand{seed}_warm70_mixup0.2_split80:10:10_linux",
    "1f": "1f_dscnn_se_res_wide_mels64_drop05_rand{seed}_warm70_mixup0.2_split80:10:10_linux",
    "1g": "1g_dscnn_se_res_att_mels64_drop05_rand{seed}_warm70_mixup0.2_split80:10:10_linux",
    "1i": "1i_mbv2_se_mels64_drop05_rand{seed}_warm70_mixup0.2_split80:10:10_linux",
    "1j": "1j_mbv3_se_mels64_drop05_rand{seed}_warm70_mixup0.2_split80:10:10_linux",
    "1p": "1p_mbv3_se_hs_mels64_drop05_rand{seed}_warm70_mixup0.2_split80:10:10_linux",
    "1q": "1q_efficientnet_se_mels64_drop05_rand{seed}_warm70_mixup0.2_split80:10:10_linux",
}

# Row pattern from sklearn classification_report
ROW_RE = re.compile(
    r"^\s*(?P<cls>[A-Za-z][A-Za-z\- ]+?)\s+"
    r"(?P<p>[01]\.\d{4})\s+(?P<r>[01]\.\d{4})\s+"
    r"(?P<f>[01]\.\d{4})\s+(?P<n>\d+)\s*$"
)


def parse_report(path: Path) -> dict[str, dict[str, float]]:
    """Return {class_name: {'precision': p, 'recall': r, 'f1': f}}."""
    out = {}
    for line in path.read_text().splitlines():
        m = ROW_RE.match(line)
        if not m:
            continue
        cls = m["cls"].strip()
        if cls in ("accuracy", "macro avg", "weighted avg"):
            continue
        out[cls] = {"precision": float(m["p"]),
                    "recall":    float(m["r"]),
                    "f1":        float(m["f"])}
    return out


def aggregate(model: str) -> dict:
    rows = {}  # class -> {metric -> [val per seed]}
    found_seeds = []
    for seed in SEEDS:
        d = RESULTS_ROOT / MODEL_DIR_PATTERN[model].format(seed=seed)
        rpt = d / "classification_report_int8.txt"
        if not rpt.exists():
            print(f"  ✗ missing seed {seed}: {rpt}", file=sys.stderr)
            continue
        found_seeds.append(seed)
        parsed = parse_report(rpt)
        for cls, metrics in parsed.items():
            slot = rows.setdefault(cls, {"precision": [], "recall": [], "f1": []})
            for k, v in metrics.items():
                slot[k].append(v)
    return rows, found_seeds


def main(models: list[str]) -> None:
    for model in models:
        if model not in MODEL_DIR_PATTERN:
            print(f"unknown model: {model}", file=sys.stderr)
            continue
        print(f"\n=== model {model} ===")
        rows, seeds = aggregate(model)
        if not rows:
            print(f"  no results found for {model}; skipping")
            continue
        if len(seeds) < 2:
            print(f"  only {len(seeds)} seed(s) found; std will be 0")
        # CSV
        csv_path = Path(f"perclass_multiseed_{model}.csv")
        with csv_path.open("w") as f:
            f.write("species,P_mean,P_std,R_mean,R_std,F1_mean,F1_std,n_seeds\n")
            for cls, m in rows.items():
                row = []
                for k in ("precision", "recall", "f1"):
                    vals = m[k]
                    mu = statistics.mean(vals)
                    sd = statistics.stdev(vals) if len(vals) > 1 else 0.0
                    row.extend([f"{mu:.4f}", f"{sd:.4f}"])
                f.write(f"{cls}," + ",".join(row) + f",{len(seeds)}\n")
        # LaTeX
        tex_path = Path(f"perclass_multiseed_{model}.tex")
        with tex_path.open("w") as f:
            f.write(
                "% Auto-generated by analyze_perclass_multiseed.py\n"
                f"% Model: {model}, seeds: {seeds}\n"
                "\\begin{tabular}{@{}lccc@{}}\n\\toprule\n"
                "\\textbf{Species} & \\textbf{Precision} & "
                "\\textbf{Recall} & \\textbf{F1} \\\\\n\\midrule\n")
            for cls, m in rows.items():
                cells = []
                for k in ("precision", "recall", "f1"):
                    vals = m[k]
                    mu = statistics.mean(vals)
                    sd = statistics.stdev(vals) if len(vals) > 1 else 0.0
                    cells.append(f"{mu:.3f} $\\pm$ {sd:.3f}")
                f.write(f"{cls} & " + " & ".join(cells) + " \\\\\n")
            f.write("\\bottomrule\n\\end{tabular}\n")
        print(f"  wrote {csv_path} and {tex_path} (seeds: {seeds})")


if __name__ == "__main__":
    args = sys.argv[1:] or ["1j"]
    main(args)
